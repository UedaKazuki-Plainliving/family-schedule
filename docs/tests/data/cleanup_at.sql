-- 受け入れテスト（AT）後のクリーンアップ
-- 実行タイミング: ATテスト完了後、または再実施の直前
-- 注意: このSQLは本番DBを変更します。実行前に必ずバックアップを確認してください。

-- ========================================
-- テスト中に追加されたメンバーを削除
-- ========================================
-- ATテストでは「おじいちゃん」などのテスト用メンバーが追加される可能性がある。
-- 予定を先に削除してからメンバーを削除する（外部キー制約のため）。

-- テスト中に追加されたメンバー（id=6以降）に紐づく予定を全て削除
DELETE FROM schedules WHERE member_id >= 6;

-- テスト中に追加されたメンバー自体を削除（初期5名 id=1〜5 は残す）
DELETE FROM members WHERE id >= 6;

-- ========================================
-- テスト用スケジュールデータを全て削除
-- ========================================
-- seed_at.sql で投入したデータと、テスト中に登録したデータを一括削除

TRUNCATE TABLE schedules RESTART IDENTITY CASCADE;

-- ========================================
-- 確認用クエリ（実行後に結果を確認する）
-- ========================================
-- 実行後に以下を実行してデータが正しくなっていることを確認：
--   SELECT * FROM members ORDER BY id;       → 5件（id=1〜5）だけ残っていること
--   SELECT COUNT(*) FROM schedules;          → 0件であること

SELECT 'メンバー数:' AS label, COUNT(*) AS count FROM members
UNION ALL
SELECT 'スケジュール数:', COUNT(*) FROM schedules;
